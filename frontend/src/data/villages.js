// Group villages by district for easier filtering
export const villagesByDistrict = villages.reduce((acc, village) => {
  if (!acc[village.district]) {
    acc[village.district] = [];
  }
  acc[village.district].push(village);
  return acc;
}, {});

// Get all unique districts
export const districts = Object.keys(villagesByDistrict).sort();

// Find village by name (case-insensitive)
export const findVillage = (name) => {
  return villages.find(v => 
    v.name.toLowerCase().includes(name.toLowerCase()) ||
    name.toLowerCase().includes(v.name.toLowerCase())
  );
};

// Get villages by district
export const getVillagesByDistrict = (district) => {
  return villagesByDistrict[district] || [];
};

